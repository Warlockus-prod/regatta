// Keep server physics generated from the shared TypeScript force model.
import { buildSync } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
const path = "ws-server/race-physics.js";
const result = buildSync({ entryPoints: ["src/lib/race-physics.ts"], outfile: path, write: false, bundle: true, platform: "neutral", format: "esm", target: "es2022", banner: { js: "// Generated by scripts/build-race-server.mjs. Do not edit by hand." } });
const output = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== output) throw new Error("Server physics is stale. Run npm run build:race-server.");
} else writeFileSync(path, output);
