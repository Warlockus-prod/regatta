// Package 32: turns the Blender renders of the yacht into the shipped part visuals.
//   Blender --background assets/3d/regatta_sloop_sailing.blend --python scripts/blender/render_part_visuals.py -- <dir>
//   node scripts/build-part-visuals.mjs <dir>
// Writes, for every part of the shared anatomy data (mobile/src/data/anatomy.json):
//   public/anatomy/parts/<part id>.webp     the picture (800x600)
//   public/anatomy/diagram/{side,top}.webp  the two schematic drawings of the whole yacht
//   src/data/anatomy-visuals.generated.ts   their sizes and where each part is on each drawing
//   mobile/assets/anatomy/**                the app's copies, with mobile/src/anatomy/part-visuals.generated.ts
// and refuses to finish when a part has no render or no place on a drawing, or a render has no
// part. src/data/anatomy-visuals.test.ts holds the same line for the shipped files.
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const PICTURE = { width: 800, height: 600 };
const VIEWS = ["side", "top"];
const source = process.argv[2];
if (!source) { console.error("usage: node scripts/build-part-visuals.mjs <directory with the Blender renders>"); process.exit(2); }
const parts = JSON.parse(readFileSync("mobile/src/data/anatomy.json", "utf8")).anatomyParts.map((part) => part.id);
const renders = readdirSync(source).filter((name) => name.endsWith(".png") && !name.startsWith("diagram-")).map((name) => name.slice(0, -4));
const drawn = JSON.parse(readFileSync(join(source, "diagram.json"), "utf8"));
const problems = [
  ...parts.filter((id) => !renders.includes(id)).map((id) => `no render for ${id}`),
  ...renders.filter((id) => !parts.includes(id)).map((id) => `render without a part: ${id}`),
  ...VIEWS.flatMap((view) => parts.filter((id) => !drawn[view]?.points?.[id]).map((id) => `${id} has no place on the ${view} drawing`)),
];
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }

let bytes = 0;
const pictures = "public/anatomy/parts", drawings = "public/anatomy/diagram";
for (const dir of [pictures, drawings]) { rmSync(dir, { recursive: true, force: true }); mkdirSync(dir, { recursive: true }); }
for (const id of parts) bytes += (await sharp(join(source, `${id}.png`)).resize(PICTURE.width, PICTURE.height, { fit: "cover" }).webp({ quality: 76, effort: 6 }).toFile(join(pictures, `${id}.webp`))).size;
const diagrams = {};
for (const view of VIEWS) {
  const info = await sharp(join(source, `diagram-${view}.png`)).webp({ quality: 82, alphaQuality: 90, effort: 6 }).toFile(join(drawings, `${view}.webp`));
  bytes += info.size;
  const points = Object.fromEntries(parts.map((id) => [id, drawn[view].points[id]]));
  diagrams[view] = { src: `/anatomy/diagram/${view}.webp`, width: info.width, height: info.height, points };
}
writeFileSync("src/data/anatomy-visuals.generated.ts", `// Generated by scripts/build-part-visuals.mjs from the Blender scene. Do not edit by hand.
// Sizes of the part pictures and of the two schematic drawings, and where each part of the
// yacht is on each drawing (fractions of the drawing's width and height from its top left).

export const PART_PICTURE_SIZE = ${JSON.stringify(PICTURE)} as const;

export const PART_DRAWINGS = ${JSON.stringify(diagrams, null, 2)} as const;
`);
// The app's native screens bundle the same files (Metro needs a static require for each).
const appAssets = "mobile/assets/anatomy";
// Only these two subfolders are ours: the folder also holds the app's other anatomy assets.
for (const dir of ["parts", "diagram"]) {
  rmSync(`${appAssets}/${dir}`, { recursive: true, force: true });
  cpSync(`public/anatomy/${dir}`, `${appAssets}/${dir}`, { recursive: true });
}
writeFileSync("mobile/src/anatomy/part-visuals.generated.ts", `// Generated by scripts/build-part-visuals.mjs. Do not edit by hand.
// The app's copies of the yacht part pictures and the two schematic drawings (mobile/assets/anatomy),
// byte-identical to public/anatomy (mobile/__tests__/part-visuals.test.tsx).

export const PART_PICTURE_ASSETS: Record<string, number> = {
${parts.map((id) => `  ${JSON.stringify(id)}: require("../../assets/anatomy/parts/${id}.webp"),`).join("\n")}
};

export const PART_DRAWING_ASSETS: Record<string, number> = {
${VIEWS.map((view) => `  ${JSON.stringify(view)}: require("../../assets/anatomy/diagram/${view}.webp"),`).join("\n")}
};
`);
console.log(`part visuals: ${parts.length} pictures and ${VIEWS.length} drawings, ${(bytes / 1024).toFixed(0)} kB`);
