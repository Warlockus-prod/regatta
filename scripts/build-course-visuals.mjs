// Package 32: turns the frames of the 3D scene into the shipped pictures of the points of sail
// and the two turns.
//   BASE_URL=http://localhost:3000 node scripts/capture-course-frames.mjs <dir>
//   node scripts/build-course-visuals.mjs <dir>
// Writes public/learning/courses/<subject>.webp (640x480), the app's copies in
// mobile/assets/learning/courses and their require map, and refuses to finish when a subject of
// src/data/sailing-visuals.ts has no frame or a frame has no subject.
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const SIZE = { width: 640, height: 480 };
const source = process.argv[2];
if (!source) { console.error("usage: node scripts/build-course-visuals.mjs <directory with the frames>"); process.exit(2); }
// The subject ids are read from the registry's text: this script runs without a TypeScript loader.
const registry = readFileSync("src/data/sailing-visuals.ts", "utf8");
const block = registry.slice(registry.indexOf("export const SAILING_SUBJECTS = {"), registry.indexOf("} as const satisfies Record<string, PointSubject | TurnSubject>"));
const subjects = [...block.matchAll(/^\s+"?([a-z-]+)"?: \{ kind:/gm)].map((match) => match[1]);
if (subjects.length < 7) throw new Error(`could not read the subjects from the registry (found ${subjects.length})`);
const frames = readdirSync(source).filter((name) => name.endsWith(".png")).map((name) => name.slice(0, -4));
const problems = [...subjects.filter((id) => !frames.includes(id)).map((id) => `no frame for ${id}`), ...frames.filter((id) => !subjects.includes(id)).map((id) => `frame without a subject: ${id}`)];
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }

const out = "public/learning/courses", app = "mobile/assets/learning/courses";
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
let bytes = 0;
for (const id of subjects) bytes += (await sharp(join(source, `${id}.png`)).resize(SIZE.width, SIZE.height, { fit: "cover" }).webp({ quality: 74, effort: 6 }).toFile(join(out, `${id}.webp`))).size;
rmSync(app, { recursive: true, force: true });
mkdirSync("mobile/assets/learning", { recursive: true });
cpSync(out, app, { recursive: true });
mkdirSync("mobile/src/learning", { recursive: true });
writeFileSync("mobile/src/learning/course-visuals.generated.ts", `// Generated by scripts/build-course-visuals.mjs. Do not edit by hand.
// The app's copies of the pictures of the points of sail and the turns (mobile/assets/learning/courses),
// byte-identical to public/learning/courses (mobile/__tests__/subject-visuals.test.tsx).

export const COURSE_PICTURE_ASSETS: Record<string, number> = {
${subjects.map((id) => `  ${JSON.stringify(id)}: require("../../assets/learning/courses/${id}.webp"),`).join("\n")}
};
`);
console.log(`course visuals: ${subjects.length} pictures, ${(bytes / 1024).toFixed(0)} kB`);
