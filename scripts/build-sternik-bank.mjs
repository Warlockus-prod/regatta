#!/usr/bin/env node
// ============================================================================
// Sternik question bank -> versioned JSON for the browser.
//
// src/data/sternik.ts is the one editable source of the 879 questions. Shipped
// as a module, it rode inside the /sternik/test and /sternik/egzamin client
// chunks (about 567 KB of JavaScript). This script writes it out as data:
//
//   public/sternik-bank/bank.<version>.json     the questions, content-hashed
//   src/data/sternik-bank-file.generated.ts     url + version + count for the client
//   public/sw.js (STERNIK_BANK_URL line)        so the offline precache stores it
//
// The version is a hash of the content, so a corrected answer gets a new file
// name: browsers and the service worker can keep a copy forever and never
// serve a stale one. Question ids are copied as they are; progress keys on them.
//
//   node scripts/build-sternik-bank.mjs           write the three outputs
//   node scripts/build-sternik-bank.mjs --check   fail if any of them is stale
//
// --check runs in the test suite (src/data/sternik-bank-file.test.ts), so CI
// catches an edited bank whose JSON was not regenerated.
// ============================================================================

import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const SCHEMA = 1;
const sourcePath = join(root, 'src/data/sternik.ts');
const bankDir = join(root, 'public/sternik-bank');
const modulePath = join(root, 'src/data/sternik-bank-file.generated.ts');
const swPath = join(root, 'public/sw.js');

// Bundle the TS source (it imports ./sternik-core) in memory and import it.
const bundled = await build({
  entryPoints: [sourcePath], bundle: true, write: false, format: 'esm', platform: 'neutral',
  logLevel: 'silent', absWorkingDir: root,
});
const mod = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);
const questions = mod.STERNIK_BANK;
if (!Array.isArray(questions) || questions.length === 0) throw new Error('STERNIK_BANK is empty');

// One question per line: compact, and a reviewable diff when one changes.
const body = questions.map((q) => JSON.stringify(q)).join(',\n');
const version = createHash('sha256').update(`schema${SCHEMA}\n${body}`).digest('hex').slice(0, 12);
const fileName = `bank.${version}.json`;
const url = `/sternik-bank/${fileName}`;
const json = `{"schema":${SCHEMA},"version":"${version}","count":${questions.length},"questions":[\n${body}\n]}\n`;

// The written file must parse back to exactly the source bank.
if (JSON.stringify(JSON.parse(json).questions) !== JSON.stringify(questions)) throw new Error('Bank JSON does not round-trip');

const moduleText = [
  '// Generated by scripts/build-sternik-bank.mjs from src/data/sternik.ts. Do not edit.',
  '// The questions themselves live in public/sternik-bank/, not in client JavaScript.',
  `export const STERNIK_BANK_FILE = { schema: ${SCHEMA}, version: '${version}', url: '${url}', count: ${questions.length} } as const;`,
  '',
].join('\n');

const SW_LINE = /^const STERNIK_BANK_URL = '[^']*';.*$/m;
const swSource = readFileSync(swPath, 'utf8');
if (!SW_LINE.test(swSource)) throw new Error('public/sw.js has no STERNIK_BANK_URL line to update');
const swText = swSource.replace(SW_LINE, `const STERNIK_BANK_URL = '${url}'; // generated by scripts/build-sternik-bank.mjs`);

const existing = existsSync(bankDir) ? readdirSync(bankDir) : [];
const stale = [];
if (check) {
  if (!existing.includes(fileName) || readFileSync(join(bankDir, fileName), 'utf8') !== json) stale.push(`public/sternik-bank/${fileName}`);
  for (const name of existing) if (name !== fileName) stale.push(`public/sternik-bank/${name} (not the current bank)`);
  if (!existsSync(modulePath) || readFileSync(modulePath, 'utf8') !== moduleText) stale.push('src/data/sternik-bank-file.generated.ts');
  if (swText !== swSource) stale.push('public/sw.js STERNIK_BANK_URL');
  if (stale.length) {
    console.error(`[sternik-bank] stale, run node scripts/build-sternik-bank.mjs:\n  ${stale.join('\n  ')}`);
    process.exit(1);
  }
} else {
  mkdirSync(bankDir, { recursive: true });
  for (const name of existing) if (name !== fileName) rmSync(join(bankDir, name));
  writeFileSync(join(bankDir, fileName), json);
  writeFileSync(modulePath, moduleText);
  if (swText !== swSource) writeFileSync(swPath, swText);
}
console.log(`sternik bank: ${questions.length} questions, ${(Buffer.byteLength(json) / 1024).toFixed(0)} KiB, ${url}${check ? ' (verified)' : ''}`);
