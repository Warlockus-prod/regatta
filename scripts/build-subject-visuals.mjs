// Package 32: turns frames of the 3D scene into the shipped pictures of the sailing subjects
// (points of sail, turns, wind, trim) and of the sail lessons.
//   BASE_URL=http://localhost:3000 node scripts/capture-subject-frames.mjs <dir> [--only id,id]
//   node scripts/build-subject-visuals.mjs <dir>
// For every frame in <dir> writes public/learning/subjects/<id>.webp (640x480); a pair
// <id>.a.png + <id>.b.png becomes one picture of two halves, before and after. Pictures that have
// no new frame stay as they are. Then it copies the folder to the app
// (mobile/assets/learning/subjects) and rewrites the app's require map.
// Which ids must have a picture is the registry's business: src/data/sailing-visuals.test.ts
// fails for a subject or a lesson without one, and for a picture nothing names.
import { cpSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const SIZE = { width: 640, height: 480 };
const source = process.argv[2];
if (!source) { console.error("usage: node scripts/build-subject-visuals.mjs <directory with the frames>"); process.exit(2); }
const out = "public/learning/subjects", app = "mobile/assets/learning/subjects";
mkdirSync(out, { recursive: true });

const frames = readdirSync(source).filter((name) => name.endsWith(".png")).map((name) => name.slice(0, -4));
const singles = frames.filter((name) => !/\.[ab]$/.test(name));
const pairs = [...new Set(frames.filter((name) => /\.[ab]$/.test(name)).map((name) => name.slice(0, -2)))];
const webp = (image) => image.webp({ quality: 74, effort: 6 });
for (const id of singles) await webp(sharp(join(source, `${id}.png`)).resize(SIZE.width, SIZE.height, { fit: "cover" })).toFile(join(out, `${id}.webp`));
for (const id of pairs) {
  // Each half is the middle of its frame, where the boat is; a paper-coloured line divides them.
  const gap = 4, half = (SIZE.width - gap) / 2;
  const [before, after] = await Promise.all(["a", "b"].map((side) => sharp(join(source, `${id}.${side}.png`)).resize(SIZE.width, SIZE.height, { fit: "cover" })
    .extract({ left: Math.round((SIZE.width - half) / 2), top: 0, width: half, height: SIZE.height }).toBuffer()));
  await webp(sharp({ create: { ...SIZE, channels: 3, background: "#f5f3ee" } }).composite([{ input: before, left: 0, top: 0 }, { input: after, left: half + gap, top: 0 }])).toFile(join(out, `${id}.webp`));
}

const pictures = readdirSync(out).filter((name) => name.endsWith(".webp")).map((name) => name.slice(0, -5)).sort();
rmSync(app, { recursive: true, force: true });
mkdirSync("mobile/assets/learning", { recursive: true });
cpSync(out, app, { recursive: true });
mkdirSync("mobile/src/learning", { recursive: true });
writeFileSync("mobile/src/learning/subject-pictures.generated.ts", `// Generated by scripts/build-subject-visuals.mjs. Do not edit by hand.
// The app's copies of the pictures of the sailing subjects and the sail lessons
// (mobile/assets/learning/subjects), byte-identical to public/learning/subjects
// (mobile/__tests__/subject-visuals.test.tsx).

export const SUBJECT_PICTURE_ASSETS: Record<string, number> = {
${pictures.map((id) => `  ${JSON.stringify(id)}: require("../../assets/learning/subjects/${id}.webp"),`).join("\n")}
};
`);
console.log(`subject visuals: ${singles.length + pairs.length} built, ${pictures.length} pictures in ${out}`);
